//! Rust consumer projection of the same validated library-owned contract.
const std = @import("std");

fn emit(out: *std.ArrayList(u8), allocator: std.mem.Allocator, comptime format: []const u8, args: anytype) !void {
    const text = try std.fmt.allocPrint(allocator, format, args);
    defer allocator.free(text);
    try out.appendSlice(allocator, text);
}
fn identifier(out: *std.ArrayList(u8), allocator: std.mem.Allocator, name: []const u8) !void {
    // Rust cannot spell these four path/receiver keywords as raw identifiers.
    for ([_][]const u8{ "self", "Self", "super", "crate" }) |special| {
        if (std.mem.eql(u8, name, special)) return emit(out, allocator, "{s}_", .{name});
    }
    try emit(out, allocator, "r#{s}", .{name});
}
fn rustType(out: *std.ArrayList(u8), allocator: std.mem.Allocator, typ: anytype) !void {
    if (typ.pointer != .value) try out.appendSlice(allocator, if (typ.is_const) "*const " else "*mut ");
    if (std.mem.eql(u8, typ.name, "void")) {
        try out.appendSlice(allocator, if (typ.pointer == .value) "()" else "core::ffi::c_void");
    } else try out.appendSlice(allocator, typ.name);
}
fn doc(out: *std.ArrayList(u8), allocator: std.mem.Allocator, text: []const u8, indent: []const u8) !void {
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |line| try emit(out, allocator, "{s}/// {s}\n", .{ indent, std.mem.trimEnd(u8, line, "\r") });
}
fn fnName(allocator: std.mem.Allocator, table: []const u8, function: []const u8) ![]u8 {
    return std.fmt.allocPrint(allocator, "{s}_{s}Fn", .{ table, function });
}

pub fn render(allocator: std.mem.Allocator, contract: anytype) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(allocator);
    try out.appendSlice(allocator, "// Generated by R4LContractGen from the library contract. Do not edit.\n#![no_std]\n#![allow(non_upper_case_globals, non_camel_case_types, clippy::too_many_arguments)]\nuse r4os_sdk::{App, r4l::{Error, Expectation, Interface, InterfaceHeader}};\n\n");
    try emit(&out, allocator, "pub const MODULE_NAME: &str = \"{s}\";\n", .{contract.module_name});
    for (contract.types) |typ| {
        try doc(&out, allocator, typ.description, "");
        try emit(&out, allocator, "#[repr(C)]\n#[derive(Clone, Copy, Debug, Default)]\npub struct {s} {{\n", .{typ.name});
        for (typ.fields) |field| {
            try doc(&out, allocator, field.description, "    ");
            try out.appendSlice(allocator, "    pub ");
            try identifier(&out, allocator, field.name);
            try out.appendSlice(allocator, ": ");
            try rustType(&out, allocator, field.type);
            try out.appendSlice(allocator, ",\n");
        }
        try emit(&out, allocator, "}}\nconst _: () = {{\n    assert!(core::mem::size_of::<{s}>() == {d});\n    assert!(core::mem::align_of::<{s}>() == {d});\n", .{ typ.name, typ.size, typ.name, typ.alignment });
        for (typ.fields) |field| {
            try emit(&out, allocator, "    assert!(core::mem::offset_of!({s}, ", .{typ.name});
            try identifier(&out, allocator, field.name);
            try emit(&out, allocator, ") == {d});\n", .{field.offset});
        }
        try out.appendSlice(allocator, "};\n\n");
    }
    for (contract.constants) |value| try emit(&out, allocator, "pub const {s}: {s} = {d};\n", .{ value.zig_name, value.type, value.value });
    for (contract.errors) |value| try emit(&out, allocator, "pub const {s}: {s} = {d};\n", .{ value.zig_name, value.type, value.value });
    for (contract.interfaces) |interface| {
        try emit(&out, allocator, "\npub const {s}_expectation: Expectation = Expectation {{ interface_id_lo: 0x{x}, interface_id_hi: 0x{x}, abi_major: {d}, min_revision: {d}, required_size: {d}, known_required_flags: {d} }};\npub const {s}_export_name: &str = \"{s}\";\n", .{ interface.zig_name, interface.interface_id_lo, interface.interface_id_hi, interface.abi_major, interface.revision, 32 + interface.functions.len * 8, interface.known_required_flags, interface.zig_name, interface.export_name });
        for (interface.functions) |function| {
            const name = try fnName(allocator, interface.zig_type, function.name);
            defer allocator.free(name);
            try emit(&out, allocator, "pub type {s} = unsafe extern \"C\" fn(", .{name});
            for (function.parameters, 0..) |parameter, index| {
                if (index != 0) try out.appendSlice(allocator, ", ");
                try identifier(&out, allocator, parameter.name);
                try out.appendSlice(allocator, ": ");
                try rustType(&out, allocator, parameter.type);
            }
            try out.appendSlice(allocator, ") -> ");
            try rustType(&out, allocator, function.returns);
            try out.appendSlice(allocator, ";\n");
        }
        try doc(&out, allocator, interface.description, "");
        try emit(&out, allocator, "#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {s} {{\n    pub header: InterfaceHeader,\n", .{interface.zig_type});
        for (interface.functions) |function| {
            const name = try fnName(allocator, interface.zig_type, function.name);
            defer allocator.free(name);
            try out.appendSlice(allocator, "    pub ");
            try identifier(&out, allocator, function.name);
            try emit(&out, allocator, ": Option<{s}>,\n", .{name});
        }
        try emit(&out, allocator, "}}\nconst _: () = {{\n    assert!(core::mem::size_of::<{s}>() == {d});\n    assert!(core::mem::align_of::<{s}>() == 8);\n", .{ interface.zig_type, 32 + interface.functions.len * 8, interface.zig_type });
        for (interface.functions) |function| {
            try emit(&out, allocator, "    assert!(core::mem::offset_of!({s}, ", .{interface.zig_type});
            try identifier(&out, allocator, function.name);
            try emit(&out, allocator, ") == {d});\n", .{32 + @as(u32, function.slot) * 8});
        }
        try emit(&out, allocator, "}};\n\npub struct {s}Client<'a> {{ interface: Interface<'a> }}\nimpl<'a> {s}Client<'a> {{\n    pub fn init(app: &'a App<'_>) -> Result<Self, Error> {{\n        let interface = Interface::new(app, MODULE_NAME, {s}_export_name, {s}_expectation)?;\n        Self::checked(interface)\n    }}\n    pub fn optional(app: &'a App<'_>) -> Result<Option<Self>, Error> {{\n        Interface::optional(app, MODULE_NAME, {s}_export_name, {s}_expectation)?.map(Self::checked).transpose()\n    }}\n    fn checked(interface: Interface<'a>) -> Result<Self, Error> {{\n", .{ interface.zig_type, interface.zig_type, interface.zig_name, interface.zig_name, interface.zig_name, interface.zig_name });
        for (interface.functions) |function| try emit(&out, allocator, "        if interface.slot_address({d}).is_none() {{ return Err(Error::MissingSlot); }}\n", .{32 + @as(u32, function.slot) * 8});
        try out.appendSlice(allocator, "        Ok(Self { interface })\n    }\n");
        for (interface.functions) |function| {
            const name = try fnName(allocator, interface.zig_type, function.name);
            defer allocator.free(name);
            try doc(&out, allocator, function.description, "    ");
            try out.appendSlice(allocator, "    /// # Safety\n");
            try doc(&out, allocator, function.operation.ownership, "    ");
            try emit(&out, allocator, "    /// Blocking: {s}; threading: {s}; reentrancy: {s}.\n", .{ @tagName(function.operation.blocking), @tagName(function.operation.threading), @tagName(function.operation.reentrancy) });
            for (function.parameters) |parameter| try emit(&out, allocator, "    /// {s}: {s}, {s}, lifetime {s}, nullable={s}.\n", .{ parameter.name, @tagName(parameter.direction), @tagName(parameter.ownership), @tagName(parameter.lifetime), if (parameter.type.nullable) "true" else "false" });
            try out.appendSlice(allocator, "    pub unsafe fn ");
            try identifier(&out, allocator, function.name);
            try out.appendSlice(allocator, "(&self");
            for (function.parameters) |parameter| {
                try out.appendSlice(allocator, ", ");
                try identifier(&out, allocator, parameter.name);
                try out.appendSlice(allocator, ": ");
                try rustType(&out, allocator, parameter.type);
            }
            try out.appendSlice(allocator, ") -> ");
            try rustType(&out, allocator, function.returns);
            try emit(&out, allocator, " {{\n        let function: {s} = unsafe {{ self.interface.function({d}) }}.expect(\"admitted R4L slot\");\n        unsafe {{ function(", .{ name, 32 + @as(u32, function.slot) * 8 });
            for (function.parameters, 0..) |parameter, index| {
                if (index != 0) try out.appendSlice(allocator, ", ");
                try identifier(&out, allocator, parameter.name);
            }
            try out.appendSlice(allocator, ") }\n    }\n");
        }
        try out.appendSlice(allocator, "}\n");
    }
    return out.toOwnedSlice(allocator);
}
